"""cruise_ai.recommendations.eval_harness — detect evaluation opportunities.

Provides:
- Test Coverage Detection: identify sessions without test commands
- Eval Harness Generation: create pytest/jest templates based on detected language
"""

from __future__ import annotations

from typing import Any

from cruise_ai.recommendations.types import Recommendation

# Known test command patterns
TEST_COMMAND_PATTERNS = [
    "pytest", "python -m pytest", "python3 -m pytest",
    "jest", "mocha", "vitest", "npm test", "npm run test",
    "yarn test", "pnpm test", "cargo test", "go test",
    "mvn test", "gradle test", "rspec", "phpunit",
    "dotnet test", "swift test",
]

# Known validate/check patterns
VALIDATE_PATTERNS = [
    "lint", "eslint", "pylint", "flake8", "ruff",
    "mypy", "tsc", "typecheck", "check",
]


def _has_test_command(commands: list[str]) -> bool:
    """Check if any command in the list is a test command."""
    for cmd in commands:
        cmd_lower = str(cmd).lower().strip()
        if any(pattern in cmd_lower for pattern in TEST_COMMAND_PATTERNS):
            return True
    return False


def _has_validate_command(commands: list[str]) -> bool:
    """Check if any command in the list is a validation command."""
    for cmd in commands:
        cmd_lower = str(cmd).lower().strip()
        if any(pattern in cmd_lower for pattern in VALIDATE_PATTERNS):
            return True
    return False


def _detect_language(scan_results: dict[str, Any]) -> str:
    """Detect primary project language from scan results."""
    stack = scan_results.get("stack", [])
    if isinstance(stack, list):
        for item in stack:
            item_lower = str(item).lower()
            if "python" in item_lower:
                return "python"
            if "javascript" in item_lower or "typescript" in item_lower or "node" in item_lower:
                return "javascript"
            if "rust" in item_lower:
                return "rust"
            if "go" in item_lower:
                return "go"
            if "java" in item_lower:
                return "java"

    # Fallback: check config files
    config_files = scan_results.get("config_files", [])
    for f in config_files:
        f_str = str(f).lower()
        if "pyproject.toml" in f_str or "setup.py" in f_str or "requirements.txt" in f_str:
            return "python"
        if "package.json" in f_str or "tsconfig" in f_str:
            return "javascript"

    return "python"


def generate_eval_harness(language: str, test_patterns: list[str]) -> dict[str, str]:
    """Generate an evaluation harness template based on detected language.

    Args:
        language: Programming language ('python', 'javascript', etc.).
        test_patterns: List of test patterns or scenarios to include.

    Returns:
        Dict with 'filename', 'content' (test template), 'description'.
    """
    try:
        if language == "javascript":
            return _generate_jest_harness(test_patterns)
        else:
            return _generate_pytest_harness(test_patterns)
    except Exception:
        return {
            "filename": "tests/test_eval.py",
            "content": "",
            "description": "Failed to generate eval harness",
        }


def _generate_pytest_harness(test_patterns: list[str]) -> dict[str, str]:
    """Generate a pytest-based eval harness."""
    test_cases = ""
    for i, pattern in enumerate(test_patterns):
        safe_name = pattern.replace(" ", "_").replace("-", "_").lower()[:40]
        test_cases += (
            f'\n\ndef test_{safe_name}():\n'
            f'    """Eval: {pattern}."""\n'
            f'    # TODO: implement evaluation for: {pattern}\n'
            f'    result = None  # replace with actual evaluation\n'
            f'    assert result is not None, "Evaluation not implemented: {pattern}"\n'
        )

    if not test_cases:
        test_cases = (
            '\n\ndef test_placeholder():\n'
            '    """Placeholder eval test."""\n'
            '    # TODO: add evaluation logic\n'
            '    assert True\n'
        )

    content = (
        '"""Evaluation harness — auto-generated by cruise-ai."""\n'
        '\n'
        'import pytest\n'
        f'{test_cases}'
    )

    return {
        "filename": "tests/test_eval_harness.py",
        "content": content,
        "description": f"Pytest evaluation harness with {len(test_patterns)} test pattern(s)",
    }


def _generate_jest_harness(test_patterns: list[str]) -> dict[str, str]:
    """Generate a Jest-based eval harness."""
    test_cases = ""
    for pattern in test_patterns:
        test_cases += (
            f'\n  it("should evaluate: {pattern}", () => {{\n'
            f'    // TODO: implement evaluation for: {pattern}\n'
            f'    const result = null; // replace with actual evaluation\n'
            f'    expect(result).not.toBeNull();\n'
            f'  }});\n'
        )

    if not test_cases:
        test_cases = (
            '\n  it("placeholder evaluation", () => {\n'
            '    // TODO: add evaluation logic\n'
            '    expect(true).toBe(true);\n'
            '  });\n'
        )

    content = (
        '// Evaluation harness — auto-generated by cruise-ai\n'
        '\n'
        'describe("Evaluation Harness", () => {'
        f'{test_cases}'
        '});\n'
    )

    return {
        "filename": "tests/eval_harness.test.js",
        "content": content,
        "description": f"Jest evaluation harness with {len(test_patterns)} test pattern(s)",
    }


def detect(
    sessions: list[Any], profile: dict[str, Any], scan_results: dict[str, Any]
) -> list[Recommendation]:
    """Detect evaluation harness opportunities.

    Recommends creating an eval harness when sessions show:
    - Repeated test/validate patterns without structure
    - Code changes made without corresponding test runs (>30% of sessions)
    """
    recs: list[Recommendation] = []

    try:
        if len(sessions) < 3:
            return recs

        sessions_without_tests = 0
        sessions_with_code_changes = 0
        test_patterns_seen: list[str] = []

        for s in sessions:
            if isinstance(s, dict):
                commands = s.get("commands", [])
            else:
                commands = getattr(s, "commands", []) or []

            commands_str = [str(c) for c in commands if c]
            has_tests = _has_test_command(commands_str)
            has_validates = _has_validate_command(commands_str)

            # Check if session has code-change indicators
            context_files = []
            if isinstance(s, dict):
                context_files = s.get("context_files", [])
            else:
                context_files = getattr(s, "context_files", []) or []

            has_code_changes = len(context_files) > 0 or any(
                "git" in str(c).lower() for c in commands_str
            )

            if has_code_changes:
                sessions_with_code_changes += 1
                if not has_tests:
                    sessions_without_tests += 1

            # Track test/validate patterns for harness generation
            if has_tests or has_validates:
                for cmd in commands_str:
                    cmd_lower = cmd.lower().strip()
                    if any(p in cmd_lower for p in TEST_COMMAND_PATTERNS + VALIDATE_PATTERNS):
                        if cmd_lower not in test_patterns_seen:
                            test_patterns_seen.append(cmd_lower)

        # Calculate ratio of sessions without tests
        total_for_ratio = max(sessions_with_code_changes, len(sessions))
        no_test_ratio = sessions_without_tests / total_for_ratio if total_for_ratio > 0 else 0

        if no_test_ratio > 0.30:
            language = _detect_language(scan_results)
            confidence = min(72, 65 + int(no_test_ratio * 10))

            recs.append(Recommendation(
                category="eval_harness",
                headline=(
                    f"{sessions_without_tests}/{total_for_ratio} sessions lack test runs "
                    f"— an eval harness would catch regressions"
                ),
                detail=(
                    f"{no_test_ratio*100:.0f}% of your sessions with code changes don't include "
                    f"test commands. An evaluation harness provides a structured way to validate "
                    f"changes before they land, preventing regressions from slipping through."
                ),
                action_type="create_eval_harness",
                trust_level="heuristic",
                confidence=confidence,
                evidence=(
                    f"{sessions_without_tests}/{total_for_ratio} sessions without tests; "
                    f"language: {language}"
                ),
                priority="medium",
                teach_text=(
                    "An evaluation harness is a structured test template that runs automatically "
                    "after code changes. Unlike ad-hoc test runs, it:\n"
                    "- Ensures consistent coverage across changes\n"
                    "- Catches regressions before they're committed\n"
                    "- Can be hooked into pre-commit or CI\n"
                    f"- Will be generated as a {language} test file you can extend"
                ),
                auto_action=f"Generate {language} eval harness with {len(test_patterns_seen)} detected pattern(s)",
                savings_estimate={
                    "sessions_without_tests": sessions_without_tests,
                    "potential_regressions_caught": sessions_without_tests,
                },
            ))

    except Exception:
        return []

    return recs
